{#
  電話番号の文字列から数字だけを抜き出す。全角数字は半角にし、「（2025年…から変更）」のように
  年を含む括弧書きは除く。0 で始まる 10〜11 桁にならなければ NULL（市外局番の無い値、番号が 2 つ書かれた値など）
#}
{% macro phone_digits(column) -%}
    nullif(
        regexp_extract(
            regexp_replace(
                regexp_replace(
                    translate({{ column }}, '０１２３４５６７８９', '0123456789'),
                    '[（(][^）)]*年[^）)]*[）)]', '', 'g'
                ),
                '[^0-9]', '', 'g'
            ),
            '^0[0-9]{9,10}$'
        ),
        ''
    )
{%- endmacro %}
